import { Commands, type Dimension, type BimState } from '@tabax/core';
import { ArrowLeftRight, Ruler, Sparkles } from 'lucide-react';
import { DebouncedNumberInput, DebouncedTextInput } from './DebouncedInputs.js';

export interface DimensionInspectorProps {
  readonly dimension: Dimension;
  readonly state: BimState;
  readonly onExecute: (cmd: Commands.Command) => void;
}

export function DimensionInspector({ dimension, onExecute }: DimensionInspectorProps) {
  const formattedValue =
    dimension.value >= 1000
      ? `${(dimension.value / 1000).toFixed(2)} m (${Math.round(dimension.value)} mm)`
      : `${Math.round(dimension.value)} mm`;

  const nature =
    dimension.references.length === 0
      ? 'Cote libre à 2 points'
      : dimension.span
        ? 'Cote de baie / trumeau (associative)'
        : dimension.references.length === 1
          ? 'Cote de mur hôte (associative)'
          : 'Cote entre axes de murs';

  return (
    <div data-testid="inspector-dimension-panel">
      <div
        style={{
          fontSize: '13px',
          fontWeight: 600,
          color: 'var(--accent-primary)',
          marginBottom: '12px',
          display: 'flex',
          alignItems: 'center',
          gap: '6px',
        }}
      >
        <Ruler size={14} />
        Cotation 2D
        {dimension.autoGenerated && (
          <span
            data-testid="dimension-auto-badge"
            style={{
              fontSize: '10px',
              padding: '2px 6px',
              borderRadius: '4px',
              backgroundColor: 'rgba(37, 99, 235, 0.15)',
              color: '#2563eb',
              display: 'inline-flex',
              alignItems: 'center',
              gap: '4px',
            }}
          >
            <Sparkles size={10} /> Auto
          </span>
        )}
      </div>

      <div style={{ fontSize: '11px', color: 'var(--text-secondary)', marginBottom: '8px' }}>
        ID : <span data-testid="dimension-id">{dimension.id}</span>
      </div>

      {/* Valeur mesurée */}
      <div style={{ marginBottom: '10px' }}>
        <label style={{ fontSize: '11px', color: 'var(--text-secondary)', fontWeight: 500 }}>
          Valeur mesurée
        </label>
        <div
          data-testid="dimension-value-display"
          style={{
            fontSize: '14px',
            fontWeight: 600,
            color: 'var(--text-primary)',
            padding: '6px 8px',
            backgroundColor: 'var(--bg-canvas-chrome)',
            borderRadius: '4px',
            border: '1px solid var(--border-subtle)',
            marginTop: '4px',
          }}
        >
          {formattedValue}
        </div>
      </div>

      {/* Déport (offset mm) */}
      <div style={{ marginBottom: '10px' }}>
        <DebouncedNumberInput
          label="Déport (mm)"
          testId="dimension-offset-input"
          value={dimension.offset}
          onChange={(offset) => {
            onExecute(new Commands.UpdateDimensionCommand(dimension.id, { offset }));
          }}
        />
      </div>

      {/* Bouton d'inversion du déport */}
      <div style={{ marginBottom: '12px' }}>
        <button
          type="button"
          data-testid="dimension-flip-offset-btn"
          onClick={() => {
            onExecute(new Commands.UpdateDimensionCommand(dimension.id, { offset: -dimension.offset }));
          }}
          style={{
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'center',
            gap: '6px',
            width: '100%',
            padding: '6px 10px',
            fontSize: '12px',
            fontWeight: 500,
            borderRadius: '4px',
            backgroundColor: 'var(--bg-card)',
            color: 'var(--text-primary)',
            border: '1px solid var(--border-subtle)',
            cursor: 'pointer',
          }}
        >
          <ArrowLeftRight size={13} />
          Inverser le côté de déport
        </button>
      </div>

      {/* Libellé surchargé (customLabel) */}
      <div style={{ marginBottom: '10px' }}>
        <DebouncedTextInput
          label="Libellé surchargé (optionnel)"
          testId="dimension-custom-label-input"
          value={dimension.customLabel ?? ''}
          onChange={(customLabel) => {
            onExecute(
              new Commands.UpdateDimensionCommand(dimension.id, {
                customLabel: customLabel.trim() || undefined,
              }),
            );
          }}
        />
      </div>

      {/* Nature géométrique */}
      <div style={{ fontSize: '11px', color: 'var(--text-secondary)', marginTop: '12px', borderTop: '1px solid var(--border-subtle)', paddingTop: '8px' }}>
        Nature : <span data-testid="dimension-nature" style={{ color: 'var(--text-primary)' }}>{nature}</span>
      </div>
    </div>
  );
}
