import { describe, it, expect, vi } from 'vitest';
import { vec2 } from '@tabax/geometry';
import {
  BimDocument,
  AddWallCommand,
  UpdateWallCommand,
  MoveWallCommand,
  DeleteWallCommand,
  AddDoorCommand,
  AutoDimensionLevelCommand,
  BimValidationError,
  DependencyGraph,
  type Door,
  type Wall,
} from './index.js';

describe('BimDocument.runTransaction & cloneForSandbox (ADR-073 Jalon 1)', () => {
  it('T-TX-01: chaîne AddWall -> MoveWall -> AddDoor -> AutoDimensionLevel en 1 seule entrée undo/redo avec DAG valide', () => {
    const doc = BimDocument.createDefaultProject();
    const levelId = Object.keys(doc.getState().levels)[0]!;
    const wallTypeId = Object.keys(doc.getState().wallTypes)[0]!;
    const doorTypeId = Object.keys(doc.getState().doorTypes)[0]!;

    // Pré-remplir avec un mur existant pour générer des cotes d'étage
    doc.execute(
      new AddWallCommand({
        id: 'w_north',
        category: 'wall',
        typeId: wallTypeId,
        levelId,
        start: vec2(0, 3000),
        end: vec2(4000, 3000),
      }),
    );

    const stateBeforeTx = doc.getState();
    const listener = vi.fn();
    doc.subscribe(listener);

    const wallId = 'w_south_ai';
    const doorId = 'd_south_ai';

    const txResult = doc.runTransaction('AI: Créer mur sud, déplacer, percer porte et coter', () => {
      doc.execute(
        new AddWallCommand({
          id: wallId,
          category: 'wall',
          typeId: wallTypeId,
          levelId,
          start: vec2(0, 0),
          end: vec2(4000, 0),
        }),
      );
      doc.execute(new MoveWallCommand(wallId, vec2(0, -500)));
      const door: Door = {
        id: doorId,
        category: 'door',
        doorTypeId,
        hostWallId: wallId,
        offsetAlong: 1500,
        swing: { side: 'left', direction: 'in' },
      };
      doc.execute(new AddDoorCommand(door));
      doc.execute(new AutoDimensionLevelCommand(levelId));
    });

    // 1 seule notification subscribe avec union dédupliquée
    expect(listener).toHaveBeenCalledTimes(1);
    const notifiedIds = listener.mock.calls[0]![0] as readonly string[];
    expect(new Set(notifiedIds).size).toBe(notifiedIds.length);
    expect(notifiedIds).toContain(wallId);
    expect(notifiedIds).toContain(doorId);
    expect(txResult.changed).toEqual(notifiedIds);

    // 1 seule entrée d'historique supplémentaire sur le plafond (1 mur préalable + 1 transaction = 2)
    expect(doc.getUndoCount()).toBe(2);
    expect(doc.getUndoLabel()).toBe('AI: Créer mur sud, déplacer, percer porte et coter');

    // Vérification géométrique issue de MoveWallCommand (y = -500) + porte + cotes automatiques
    const stateAfterTx = doc.getState();
    expect(stateAfterTx.walls[wallId]?.start.y).toBe(-500);
    expect(stateAfterTx.doors[doorId]?.hostWallId).toBe(wallId);
    const autoDims = Object.values(stateAfterTx.dimensions).filter((d) => d.autoGenerated === true);
    expect(autoDims.length).toBeGreaterThan(0);
    expect(doc.getDependencyGraph().equals(DependencyGraph.build(stateAfterTx))).toBe(true);

    // Undo unique annule toute la chaîne et passe la validation DAG sur clone (ADR-070 D3)
    expect(doc.undo()).toBe(true);
    expect(doc.getUndoCount()).toBe(1);
    expect(doc.getRedoCount()).toBe(1);
    expect(doc.getRedoLabel()).toBe('AI: Créer mur sud, déplacer, percer porte et coter');
    expect(doc.getState()).toEqual(stateBeforeTx);
    expect(doc.getDependencyGraph().equals(DependencyGraph.build(doc.getState()))).toBe(true);

    // Redo unique rétablit toute la chaîne et préserve la cohérence DAG
    expect(doc.redo()).toBe(true);
    expect(doc.getUndoCount()).toBe(2);
    expect(doc.getRedoCount()).toBe(0);
    expect(doc.getState()).toEqual(stateAfterTx);
    expect(doc.getDependencyGraph().equals(DependencyGraph.build(doc.getState()))).toBe(true);
  });

  it('T-TX-02: rollback complet sur erreur à l’étape k (state, _dag et historique strictement invariants)', () => {
    const doc = BimDocument.createDefaultProject();
    const levelId = Object.keys(doc.getState().levels)[0]!;
    const wallTypeId = Object.keys(doc.getState().wallTypes)[0]!;
    const doorTypeId = Object.keys(doc.getState().doorTypes)[0]!;

    const stateBefore = doc.getState();
    const dagBefore = doc.getDependencyGraph();
    const listener = vi.fn();
    doc.subscribe(listener);

    expect(() => {
      doc.runTransaction('Transaction en échec à étape 2', () => {
        doc.execute(
          new AddWallCommand({
            id: 'w_tx_ok',
            category: 'wall',
            typeId: wallTypeId,
            levelId,
            start: vec2(0, 0),
            end: vec2(3000, 0),
          }),
        );
        // Offset invalide hors du mur -> BimValidationError dans validateDoor
        doc.execute(
          new AddDoorCommand({
            id: 'd_tx_fail',
            category: 'door',
            doorTypeId,
            hostWallId: 'w_tx_ok',
            offsetAlong: 10_000,
            swing: { side: 'left', direction: 'in' },
          }),
        );
      });
    }).toThrow(BimValidationError);

    expect(doc.getState()).toBe(stateBefore);
    expect(doc.getDependencyGraph()).toBe(dagBefore);
    expect(doc.canUndo()).toBe(false);
    expect(doc.canRedo()).toBe(false);
    expect(doc.getUndoCount()).toBe(0);
    expect(listener).not.toHaveBeenCalled();
  });

  it('T-TX-03: une transaction vide (0 commande) est un no-op pur sans historique ni notification', () => {
    const doc = BimDocument.createDefaultProject();
    const stateBefore = doc.getState();
    const listener = vi.fn();
    doc.subscribe(listener);

    const res = doc.runTransaction('Transaction vide', () => {
      // Aucune commande exécutée
    });

    expect(res.changed).toEqual([]);
    expect(res.patches).toEqual([]);
    expect(res.inversePatches).toEqual([]);
    expect(doc.getState()).toBe(stateBefore);
    expect(doc.canUndo()).toBe(false);
    expect(doc.getUndoCount()).toBe(0);
    expect(listener).not.toHaveBeenCalled();
  });

  it('T-TX-04: rejette toute transaction imbriquée (ou undo/redo interne) et restaure proprement l’état', () => {
    const doc = BimDocument.createDefaultProject();
    const levelId = Object.keys(doc.getState().levels)[0]!;
    const wallTypeId = Object.keys(doc.getState().wallTypes)[0]!;
    const stateBefore = doc.getState();
    const listener = vi.fn();
    doc.subscribe(listener);

    expect(() => {
      doc.runTransaction('Externe', () => {
        doc.execute(
          new AddWallCommand({
            id: 'w_nested_test',
            category: 'wall',
            typeId: wallTypeId,
            levelId,
            start: vec2(0, 0),
            end: vec2(2000, 0),
          }),
        );
        doc.runTransaction('Interne interdite', () => {});
      });
    }).toThrow(BimValidationError);

    expect(doc.getState()).toBe(stateBefore);
    expect(doc.canUndo()).toBe(false);
    expect(listener).not.toHaveBeenCalled();

    // Vérifier aussi que undo() à l'intérieur d'une transaction est rejeté proprement
    expect(() => {
      doc.runTransaction('Undo interdit', () => {
        doc.undo();
      });
    }).toThrow(BimValidationError);

    // Vérifier que le verrou activeTransaction a bien été libéré dans finally
    const afterRes = doc.runTransaction('Reprise après erreur', () => {
      doc.execute(
        new AddWallCommand({
          id: 'w_after_nested',
          category: 'wall',
          typeId: wallTypeId,
          levelId,
          start: vec2(0, 0),
          end: vec2(2000, 0),
        }),
      );
    });
    expect(afterRes.changed).toContain('w_after_nested');
    expect(doc.getState().walls['w_after_nested']).toBeDefined();
  });

  it('T-TX-05: gère proprement la création suivie de suppression d’un même élément dans une transaction', () => {
    const doc = BimDocument.createDefaultProject();
    const levelId = Object.keys(doc.getState().levels)[0]!;
    const wallTypeId = Object.keys(doc.getState().wallTypes)[0]!;
    const doorTypeId = Object.keys(doc.getState().doorTypes)[0]!;
    const stateBefore = doc.getState();

    const tempWall: Wall = {
      id: 'w_ephemeral',
      category: 'wall',
      typeId: wallTypeId,
      levelId,
      start: vec2(0, 0),
      end: vec2(3000, 0),
    };

    const res = doc.runTransaction('Création + suppression éphémère', () => {
      doc.execute(new AddWallCommand(tempWall));
      doc.execute(
        new AddDoorCommand({
          id: 'd_ephemeral',
          category: 'door',
          doorTypeId,
          hostWallId: tempWall.id,
          offsetAlong: 1000,
          swing: { side: 'left', direction: 'in' },
        }),
      );
      doc.execute(new DeleteWallCommand(tempWall.id));
    });

    expect(res.changed).toContain('w_ephemeral');
    expect(res.changed).toContain('d_ephemeral');
    expect(doc.getState().walls['w_ephemeral']).toBeUndefined();
    expect(doc.getState().doors['d_ephemeral']).toBeUndefined();
    expect(doc.getDependencyGraph().equals(DependencyGraph.build(doc.getState()))).toBe(true);

    // Undo / Redo doivent traverser sans erreur un ID absent de beforeState et afterState
    expect(doc.undo()).toBe(true);
    expect(doc.getState()).toEqual(stateBefore);
    expect(doc.getDependencyGraph().equals(DependencyGraph.build(doc.getState()))).toBe(true);

    expect(doc.redo()).toBe(true);
    expect(doc.getState().walls['w_ephemeral']).toBeUndefined();
    expect(doc.getDependencyGraph().equals(DependencyGraph.build(doc.getState()))).toBe(true);
  });

  it('T-TX-06: concaténation inversée des inversePatches (création + mise à jour sur même entité puis undo/redo)', () => {
    const doc = BimDocument.createDefaultProject();
    const levelId = Object.keys(doc.getState().levels)[0]!;
    const wallTypeId = Object.keys(doc.getState().wallTypes)[0]!;
    const stateBefore = doc.getState();

    doc.runTransaction('Créer puis modifier le même mur', () => {
      doc.execute(
        new AddWallCommand({
          id: 'w_patch_order',
          category: 'wall',
          typeId: wallTypeId,
          levelId,
          start: vec2(0, 0),
          end: vec2(3000, 0),
        }),
      );
      doc.execute(
        new UpdateWallCommand('w_patch_order', {
          end: vec2(4500, 0),
          heightOverride: 3200,
        }),
      );
    });

    expect(doc.getState().walls['w_patch_order']?.end.x).toBe(4500);
    expect(doc.getState().walls['w_patch_order']?.heightOverride).toBe(3200);

    expect(doc.undo()).toBe(true);
    expect(doc.getState()).toEqual(stateBefore);
    expect(doc.getState().walls['w_patch_order']).toBeUndefined();

    expect(doc.redo()).toBe(true);
    expect(doc.getState().walls['w_patch_order']?.end.x).toBe(4500);
    expect(doc.getState().walls['w_patch_order']?.heightOverride).toBe(3200);
  });

  it('T-TX-07: cloneForSandbox() partage l’état initial sans copier l’historique ni les abonnés et isole toute mutation', () => {
    const doc = BimDocument.createDefaultProject();
    const levelId = Object.keys(doc.getState().levels)[0]!;
    const wallTypeId = Object.keys(doc.getState().wallTypes)[0]!;

    doc.execute(
      new AddWallCommand({
        id: 'w_base',
        category: 'wall',
        typeId: wallTypeId,
        levelId,
        start: vec2(0, 0),
        end: vec2(3000, 0),
      }),
    );

    const sourceStateBefore = doc.getState();
    const sourceListener = vi.fn();
    doc.subscribe(sourceListener);

    const sandbox = doc.cloneForSandbox();
    expect(sandbox.getState()).toBe(sourceStateBefore);
    expect(sandbox.canUndo()).toBe(false);
    expect(sandbox.canRedo()).toBe(false);
    expect(sandbox.getUndoCount()).toBe(0);

    const sandboxListener = vi.fn();
    sandbox.subscribe(sandboxListener);

    sandbox.runTransaction('Mutation en bac à sable', () => {
      sandbox.execute(
        new AddWallCommand({
          id: 'w_sandbox_only',
          category: 'wall',
          typeId: wallTypeId,
          levelId,
          start: vec2(3000, 0),
          end: vec2(3000, 3000),
        }),
      );
    });

    expect(sandbox.getState().walls['w_sandbox_only']).toBeDefined();
    expect(sandbox.canUndo()).toBe(true);
    expect(sandboxListener).toHaveBeenCalledTimes(1);

    // Le document source reste strictement intouché et silencieux
    expect(doc.getState()).toBe(sourceStateBefore);
    expect(doc.getState().walls['w_sandbox_only']).toBeUndefined();
    expect(sourceListener).not.toHaveBeenCalled();
    expect(doc.getDependencyGraph().equals(DependencyGraph.build(doc.getState()))).toBe(true);
  });
});
