import { describe, it, expect } from 'vitest';
import {
  AddSectionCutCommand,
  AutoGenerateViewsCommand,
  computeAutoSectionViews,
  createComplexVillaDocument,
  type SectionCut,
} from '../index.js';
import { vec2 } from '@tabax/geometry';

describe('Saison 3 — Étape 5 (Axe 1) : Moteur de Génération Automatique de Vues (AutoGenerateViewsCommand)', () => {
  it('génère 6 vues architecturales (4 élévations + 2 coupes orthogonales) avec orientations d’observateur exactes', () => {
    const doc = createComplexVillaDocument();
    const state = doc.getState();

    const views = computeAutoSectionViews(state);
    expect(views).toHaveLength(6);

    const elevations = views.filter((v) => v.kind === 'elevation');
    const sections = views.filter((v) => v.kind === 'section');

    expect(elevations).toHaveLength(4);
    expect(sections).toHaveLength(2);

    // Vérification de la Façade Sud
    const sud = elevations.find((e) => e.label === 'S');
    expect(sud).toBeDefined();
    expect(sud!.name).toBe('Élévation Façade Sud');
    expect(sud!.start.x).toBeLessThan(sud!.end.x); // De l'Ouest vers l'Est
    expect(sud!.start.y).toBe(sud!.end.y); // Ligne horizontale au Sud
    expect(sud!.viewDirection).toBe(1); // Regard vers le Nord

    // Vérification de la Façade Nord
    const nord = elevations.find((e) => e.label === 'N');
    expect(nord).toBeDefined();
    expect(nord!.name).toBe('Élévation Façade Nord');
    expect(nord!.start.x).toBeGreaterThan(nord!.end.x); // De l'Est vers l'Ouest
    expect(nord!.start.y).toBe(nord!.end.y); // Ligne horizontale au Nord
    expect(nord!.viewDirection).toBe(1); // Tangente (-1, 0) -> normale gauche (0, -1) = Sud

    // Vérification de la Façade Ouest
    const ouest = elevations.find((e) => e.label === 'O');
    expect(ouest).toBeDefined();
    expect(ouest!.name).toBe('Élévation Façade Ouest');
    expect(ouest!.start.y).toBeGreaterThan(ouest!.end.y); // Du Nord vers le Sud
    expect(ouest!.start.x).toBe(ouest!.end.x); // Ligne verticale à l'Ouest
    expect(ouest!.viewDirection).toBe(1); // Tangente (0, -1) -> normale gauche (1, 0) = Est

    // Vérification de la Façade Est
    const est = elevations.find((e) => e.label === 'E');
    expect(est).toBeDefined();
    expect(est!.name).toBe('Élévation Façade Est');
    expect(est!.start.y).toBeLessThan(est!.end.y); // Du Sud vers le Nord
    expect(est!.start.x).toBe(est!.end.x); // Ligne verticale à l'Est
    expect(est!.viewDirection).toBe(1); // Tangente (0, 1) -> normale gauche (-1, 0) = Ouest

    // Vérification des coupes transversale et longitudinale
    const coupeA = sections.find((s) => s.label === 'A');
    const coupeB = sections.find((s) => s.label === 'B');
    expect(coupeA).toBeDefined();
    expect(coupeA!.name).toBe("Coupe transversale A-A'");
    expect(coupeB).toBeDefined();
    expect(coupeB!.name).toBe("Coupe longitudinale B-B'");

    // Toutes les vues portent le flag autoGenerated: true
    for (const v of views) {
      expect(v.autoGenerated).toBe(true);
    }
  });

  it('exécute AutoGenerateViewsCommand de manière idempotente sans altérer les coupes manuelles', () => {
    const doc = createComplexVillaDocument();

    // 1. L'utilisateur crée une coupe manuelle
    const manualCut: SectionCut = {
      id: 'manual_cut_user_1',
      category: 'sectionCut',
      name: 'Ma Coupe Personnalisée',
      label: 'X',
      kind: 'section',
      start: vec2(2000, 2000),
      end: vec2(6000, 2000),
      viewDirection: 1,
      depth: 5000,
      autoGenerated: false,
    };
    doc.execute(new AddSectionCutCommand(manualCut));
    expect(doc.getState().sectionCuts?.[manualCut.id]).toBeDefined();

    // 2. Première génération automatique
    doc.execute(new AutoGenerateViewsCommand());
    const state1 = doc.getState();
    const cuts1 = Object.values(state1.sectionCuts ?? {});
    // 1 coupe manuelle + 6 vues auto-générées = 7 vues
    expect(cuts1).toHaveLength(7);
    expect(state1.sectionCuts?.[manualCut.id]).toBeDefined();

    const autoViews1 = cuts1.filter((c) => c.autoGenerated === true);
    expect(autoViews1).toHaveLength(6);
    const ids1 = new Set(autoViews1.map((v) => v.id));

    // 3. Deuxième génération automatique (idempotence)
    doc.execute(new AutoGenerateViewsCommand());
    const state2 = doc.getState();
    const cuts2 = Object.values(state2.sectionCuts ?? {});
    // Toujours 7 vues au total, la coupe manuelle est strictement préservée
    expect(cuts2).toHaveLength(7);
    expect(state2.sectionCuts?.[manualCut.id]).toBeDefined();
    expect(state2.sectionCuts?.[manualCut.id]?.name).toBe('Ma Coupe Personnalisée');

    const autoViews2 = cuts2.filter((c) => c.autoGenerated === true);
    expect(autoViews2).toHaveLength(6);

    // 4. Undo rétablit l'état précédent
    doc.undo();
    const stateUndo = doc.getState();
    const cutsUndo = Object.values(stateUndo.sectionCuts ?? {});
    expect(cutsUndo).toHaveLength(7);
    for (const c of cutsUndo.filter((v) => v.autoGenerated === true)) {
      expect(ids1.has(c.id)).toBe(true);
    }
  });
});
