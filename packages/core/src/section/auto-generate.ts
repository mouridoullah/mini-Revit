/**
 * @tabax/core/section/auto-generate
 *
 * Moteur de génération automatique de vues architecturales (Coupes et Élévations).
 * Produit de manière idempotente :
 * - 4 élévations de façades extérieures (Sud, Nord, Ouest, Est) avec orientation d'observateur rigoureuse
 * - 2 coupes orthogonales stratégiques (A-A' transversale et B-B' longitudinale traversant escaliers ou barycentre)
 */

import { vec2, type Vec2 } from '@tabax/geometry';
import type { BimState, SectionCut, ElementId } from '../types.js';
import type { Command } from '../commands/base.js';
import { generateId } from '../ids.js';
import { validateSectionCut } from '../rules/section-cuts.js';

export const AUTO_VIEWS_MARGIN_MM = 1500;

export interface AutoViewsBoundingBox {
  readonly xMin: number;
  readonly xMax: number;
  readonly yMin: number;
  readonly yMax: number;
  readonly cutX: number;
  readonly cutY: number;
}

/**
 * Calcule l'emprise englobante 2D globale de l'ensemble de la maquette (tous niveaux confondus).
 */
export function computeModelBounds2D(state: BimState): AutoViewsBoundingBox {
  const points: Vec2[] = [];

  // Murs
  for (const wall of Object.values(state.walls ?? {})) {
    points.push(wall.start, wall.end);
  }

  // Dalles
  for (const slab of Object.values(state.slabs ?? {})) {
    if (slab.boundary) {
      for (const pt of slab.boundary) {
        points.push(pt);
      }
    }
  }

  // Toitures
  for (const roof of Object.values(state.roofs ?? {})) {
    if (roof.footprint) {
      for (const pt of roof.footprint) {
        points.push(pt);
      }
    }
  }

  let xMin = Infinity;
  let xMax = -Infinity;
  let yMin = Infinity;
  let yMax = -Infinity;

  if (points.length === 0) {
    xMin = 0;
    xMax = 10000;
    yMin = 0;
    yMax = 8000;
  } else {
    for (const pt of points) {
      if (pt.x < xMin) xMin = pt.x;
      if (pt.x > xMax) xMax = pt.x;
      if (pt.y < yMin) yMin = pt.y;
      if (pt.y > yMax) yMax = pt.y;
    }
  }

  // Emplacement privilégié des coupes orthogonales (axe d'escalier ou barycentre)
  const stairs = Object.values(state.stairs ?? {});
  let cutX = (xMin + xMax) / 2;
  let cutY = (yMin + yMax) / 2;

  if (stairs.length > 0 && stairs[0]) {
    const st = stairs[0];
    cutX = Math.round((st.start.x + st.end.x) / 2);
    cutY = Math.round((st.start.y + st.end.y) / 2);
  } else {
    const rooms = Object.values(state.rooms ?? {});
    if (rooms.length > 0) {
      let sumX = 0;
      let sumY = 0;
      let count = 0;
      for (const r of rooms) {
        if (r.seed) {
          sumX += r.seed.x;
          sumY += r.seed.y;
          count++;
        }
      }
      if (count > 0) {
        cutX = Math.round(sumX / count);
        cutY = Math.round(sumY / count);
      }
    }
  }

  return {
    xMin,
    xMax,
    yMin,
    yMax,
    cutX,
    cutY,
  };
}

/**
 * Calcule analytiquement les 6 coupes et élévations automatiques pour la maquette.
 */
export function computeAutoSectionViews(state: BimState): SectionCut[] {
  const bounds = computeModelBounds2D(state);
  const m = AUTO_VIEWS_MARGIN_MM;

  const xMin = bounds.xMin - m;
  const xMax = bounds.xMax + m;
  const yMin = bounds.yMin - m;
  const yMax = bounds.yMax + m;

  const widthX = xMax - xMin;
  const depthY = yMax - yMin;

  const cuts: SectionCut[] = [];

  // 1. Coupe transversale A-A'
  cuts.push({
    id: generateId(),
    category: 'sectionCut',
    name: "Coupe transversale A-A'",
    label: 'A',
    kind: 'section',
    start: vec2(xMin, bounds.cutY),
    end: vec2(xMax, bounds.cutY),
    viewDirection: 1,
    depth: Math.round(depthY / 2 + m),
    autoGenerated: true,
  });

  // 2. Coupe longitudinale B-B'
  cuts.push({
    id: generateId(),
    category: 'sectionCut',
    name: "Coupe longitudinale B-B'",
    label: 'B',
    kind: 'section',
    start: vec2(bounds.cutX, yMin),
    end: vec2(bounds.cutX, yMax),
    viewDirection: 1,
    depth: Math.round(widthX / 2 + m),
    autoGenerated: true,
  });

  // 3. Façade Sud (regard vers le Nord +Y)
  // Observateur au Sud : gauche = Ouest (xMin), droite = Est (xMax)
  cuts.push({
    id: generateId(),
    category: 'sectionCut',
    name: 'Élévation Façade Sud',
    label: 'S',
    kind: 'elevation',
    start: vec2(xMin, yMin),
    end: vec2(xMax, yMin),
    viewDirection: 1, // Normale gauche (0, 1) vers +Y
    depth: Math.round(depthY + m),
    autoGenerated: true,
  });

  // 4. Façade Nord (regard vers le Sud -Y)
  // Observateur au Nord : gauche = Est (xMax), droite = Ouest (xMin)
  cuts.push({
    id: generateId(),
    category: 'sectionCut',
    name: 'Élévation Façade Nord',
    label: 'N',
    kind: 'elevation',
    start: vec2(xMax, yMax),
    end: vec2(xMin, yMax),
    viewDirection: 1, // Tangente (-1, 0) -> normale gauche (0, -1) vers -Y
    depth: Math.round(depthY + m),
    autoGenerated: true,
  });

  // 5. Façade Ouest (regard vers l'Est +X)
  // Observateur à l'Ouest : gauche = Nord (yMax), droite = Sud (yMin)
  cuts.push({
    id: generateId(),
    category: 'sectionCut',
    name: 'Élévation Façade Ouest',
    label: 'O',
    kind: 'elevation',
    start: vec2(xMin, yMax),
    end: vec2(xMin, yMin),
    viewDirection: 1, // Tangente (0, -1) -> normale gauche (1, 0) vers +X
    depth: Math.round(widthX + m),
    autoGenerated: true,
  });

  // 6. Façade Est (regard vers l'Ouest -X)
  // Observateur à l'Est : gauche = Sud (yMin), droite = Nord (yMax)
  cuts.push({
    id: generateId(),
    category: 'sectionCut',
    name: 'Élévation Façade Est',
    label: 'E',
    kind: 'elevation',
    start: vec2(xMax, yMin),
    end: vec2(xMax, yMax),
    viewDirection: 1, // Tangente (0, 1) -> normale gauche (-1, 0) vers -X
    depth: Math.round(widthX + m),
    autoGenerated: true,
  });

  return cuts;
}

/**
 * Commande transactionnelle atomique générant automatiquement les 4 élévations de façades
 * et les 2 coupes orthogonales du projet.
 *
 * Idempotence stricte : supprime et remplace exclusivement les vues ayant `autoGenerated === true`,
 * sans jamais supprimer ni modifier les coupes ou élévations manuelles tracées par l'utilisateur.
 */
export class AutoGenerateViewsCommand implements Command {
  public readonly name = 'AutoGenerateViews';
  private changedIds: ElementId[] = [];

  public apply(draft: BimState): void {
    const sectionCuts = ((draft as { sectionCuts: Record<ElementId, SectionCut> }).sectionCuts ??= {});
    const changed: ElementId[] = [];

    // 1. Suppression idempotente des anciennes vues auto-générées
    for (const [id, cut] of Object.entries(sectionCuts)) {
      if (cut.autoGenerated === true) {
        Reflect.deleteProperty(sectionCuts, id);
        changed.push(id);
      }
    }

    // 2. Calcul et insertion des 6 nouvelles vues automatiques
    const newViews = computeAutoSectionViews(draft);
    for (const view of newViews) {
      validateSectionCut(view, draft);
      sectionCuts[view.id] = view;
      changed.push(view.id);
    }

    this.changedIds = changed;
  }

  public getChangedIds(): readonly ElementId[] {
    return this.changedIds;
  }
}
