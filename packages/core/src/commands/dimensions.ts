import type { Command } from './base.js';
import type { Dimension, BimState, ElementId } from '../types.js';
import { validateDimension, BimValidationError } from '../rules/index.js';
import { computeDimensionValue, computeAutoDimensionsForLevel } from '../dimensions/index.js';

export class AddDimensionCommand implements Command {
  public readonly name = 'AddDimension';

  public constructor(public readonly dimension: Dimension) {}

  public apply(draft: BimState): void {
    if (draft.dimensions && draft.dimensions[this.dimension.id]) {
      throw new BimValidationError(
        'ELEMENT_ALREADY_EXISTS',
        `A dimension with ID "${this.dimension.id}" already exists.`,
      );
    }
    validateDimension(this.dimension, draft as BimState);
    const computedValue = computeDimensionValue(this.dimension, draft as BimState);
    const dimToStore: Dimension = {
      ...this.dimension,
      value: computedValue,
    };
    const dimensions =
      (draft as { dimensions: Record<ElementId, Dimension> }).dimensions ??
      ((draft as { dimensions: Record<ElementId, Dimension> }).dimensions = {});
    dimensions[this.dimension.id] = dimToStore;
  }

  public getChangedIds(): readonly ElementId[] {
    return [this.dimension.id];
  }
}

export class UpdateDimensionCommand implements Command {
  public readonly name = 'UpdateDimension';

  public constructor(
    public readonly dimensionId: ElementId,
    public readonly patch: Partial<Omit<Dimension, 'id' | 'category'>>,
  ) {}

  public apply(draft: BimState): void {
    const existing = draft.dimensions?.[this.dimensionId];
    if (!existing) {
      throw new BimValidationError(
        'ELEMENT_NOT_FOUND',
        `Cannot update dimension: ID "${this.dimensionId}" not found.`,
      );
    }

    const updated: Dimension = {
      ...existing,
      ...this.patch,
      id: existing.id,
      category: 'dimension',
    };

    validateDimension(updated, draft as BimState);
    const finalUpdated: Dimension = {
      ...updated,
      value: computeDimensionValue(updated, draft as BimState),
    };
    draft.dimensions[this.dimensionId] = finalUpdated;
  }

  public getChangedIds(): readonly ElementId[] {
    return [this.dimensionId];
  }
}

export class DeleteDimensionCommand implements Command {
  public readonly name = 'DeleteDimension';

  public constructor(public readonly dimensionId: ElementId) {}

  public apply(draft: BimState): void {
    if (!draft.dimensions?.[this.dimensionId]) {
      throw new BimValidationError(
        'ELEMENT_NOT_FOUND',
        `Cannot delete dimension: ID "${this.dimensionId}" not found.`,
      );
    }
    Reflect.deleteProperty(draft.dimensions, this.dimensionId);
  }

  public getChangedIds(): readonly ElementId[] {
    return [this.dimensionId];
  }
}

/**
 * Commande transactionnelle atomique générant automatiquement les chaînes de cotation 2D
 * pour l'ensemble d'un étage (trumeaux, baies, et cote hors-tout globale).
 *
 * Idempotence garantie : remplace uniquement les cotes `autoGenerated: true` du niveau cible,
 * sans jamais altérer ni écraser les cotes manuelles posées par l'utilisateur.
 */
export class AutoDimensionLevelCommand implements Command {
  public readonly name = 'AutoDimensionLevel';
  private changedIds: ElementId[] = [];

  public constructor(public readonly levelId: ElementId) {}

  public apply(draft: BimState): void {
    if (!draft.levels?.[this.levelId]) {
      throw new BimValidationError(
        'UNKNOWN_LEVEL',
        `Cannot auto-dimension non-existent Level ID "${this.levelId}".`,
      );
    }

    const dimensions =
      (draft as { dimensions: Record<ElementId, Dimension> }).dimensions ??
      ((draft as { dimensions: Record<ElementId, Dimension> }).dimensions = {});

    const changed: ElementId[] = [];

    // 1. Suppression idempotente des anciennes cotes automatiques de ce niveau
    for (const [id, dim] of Object.entries(dimensions)) {
      if (dim.levelId === this.levelId && dim.autoGenerated === true) {
        Reflect.deleteProperty(dimensions, id);
        changed.push(id);
      }
    }

    // 2. Génération des nouvelles cotes pour l'étage
    const newDims = computeAutoDimensionsForLevel(draft as BimState, this.levelId);
    for (const dim of newDims) {
      validateDimension(dim, draft as BimState);
      dimensions[dim.id] = dim;
      changed.push(dim.id);
    }

    this.changedIds = changed;
  }

  public getChangedIds(): readonly ElementId[] {
    return this.changedIds;
  }
}
